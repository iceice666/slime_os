pub fn glyph(character: u8) -> Option<[u8; GLYPH_HEIGHT]> {
    glyph_index(character).map(|index| FONT[index])
}

fn glyph_index(character: u8) -> Option<usize> {
    let character = if character.is_ascii_lowercase() {
        character - (b'a' - b'A')
    } else {
        character
    };

    match character {
        b' ' => Some(0),
        b'0'..=b'9' => Some(1 + (character - b'0') as usize),
        b'A'..=b'Z' => Some(11 + (character - b'A') as usize),
        b'-' => Some(37),
        b'_' => Some(38),
        b'=' => Some(39),
        b':' => Some(40),
        b'.' => Some(41),
        b'/' => Some(42),
        b'>' => Some(43),
        b'(' => Some(44),
        b')' => Some(45),
        b',' => Some(46),
        b'+' => Some(47),
        b'*' => Some(48),
        b'!' => Some(49),
        b'?' => Some(50),
        b'%' => Some(51),
        b'#' => Some(52),
        b'[' => Some(53),
        b']' => Some(54),
        _ => None,
    }
}
