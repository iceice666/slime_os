"""Judge the wire records of `contracts/zenoh-service-client/v1`: the encoders and decoders a holder and the service share.

`zenoh_client_exam` judges the schema as text and the constants file it renders. This module renders the four records
(the request, the completion, the sample header and the loan descriptor) as Rust structs from the schema's layouts,
and judges two things about the file the implementation commits:

* it equals the rendered text byte for byte, so no field offset is written by hand;
* the Rust test that encodes and decodes each record prints bytes equal to what `struct.pack` writes from the same
  values and the same layout, so a width, an offset, a sign or a byte order the renderer got wrong is seen.

The reference is Python's `struct` and the schema's layout, never the Rust. Like the other judges it is trusted
only after it refuses a mutation of an honest transcript and of an honest file.
"""

from __future__ import annotations

import re
import struct
import subprocess

import zenoh_client_exam as client
from harness import ROOT

GENERATED = ROOT / "components" / "proto" / "src" / "zenoh_service_client_wire.rs"
GENERATED_HEADER = (
    "// @generated by scripts/generate/generate-zenoh-service-client-wire.py; do not edit.\n"
    "// Source contract: contracts/zenoh-service-client/v1/schema.zt\n"
)

# (record type, layout name, struct name, offset and length prefix)
RECORDS = (
    ("ServiceRequest", "requestLayout", "WireServiceRequest", "REQUEST"),
    ("ServiceCompletion", "completionLayout", "WireServiceCompletion", "COMPLETION"),
    ("SampleHeader", "sampleHeaderLayout", "WireSampleHeader", "SAMPLE_HEADER"),
    ("ServiceLoan", "loanLayout", "WireServiceLoan", "LOAN"),
)
RECORD_WORDS = {"ServiceRequest": "request", "ServiceCompletion": "completion", "SampleHeader": "header", "ServiceLoan": "loan"}


class WireError(Exception):
    pass


def _need(condition: bool, message: str) -> None:
    if not condition:
        raise WireError(message)


def rust_type(width: int, signed: bool, array: bool) -> str:
    if array:
        return f"[u8; {width}]"
    _need(width in (1, 2, 4, 8), f"wire: a field of {width} bytes has no integer type")
    return f"{'i' if signed else 'u'}{width * 8}"


def _decode_expr(prefix: str, name: str, width: int, signed: bool, array: bool) -> str:
    offset = f"OFF_{prefix}_{name.upper()}"
    if array:
        return f'buf[{offset}..{offset} + {width}].try_into().expect("generated layout")'
    if width == 1:
        return f"buf[{offset}]" if not signed else f"buf[{offset}] as i8"
    return f'{rust_type(width, signed, False)}::from_le_bytes(buf[{offset}..{offset} + {width}].try_into().expect("generated layout"))'


def _encode_stmt(prefix: str, name: str, width: int, signed: bool, array: bool) -> str:
    offset = f"OFF_{prefix}_{name.upper()}"
    if array:
        return f"buf[{offset}..{offset} + {width}].copy_from_slice(&self.{name});"
    if width == 1:
        return f"buf[{offset}] = self.{name}{' as u8' if signed else ''};"
    return f"buf[{offset}..{offset} + {width}].copy_from_slice(&self.{name}.to_le_bytes());"


def render_raw(text: str | None = None) -> str:
    """The Rust file before rustfmt: one struct per record, with offsets taken from the layout in field order."""
    text = client.SCHEMA.read_text(encoding="utf-8") if text is None else text
    found = client.constants(text)
    out = [GENERATED_HEADER, "\n"]
    for record, layout_name, struct_name, prefix in RECORDS:
        fields = client.layout(text, layout_name)
        _need(fields, f"wire: {layout_name} has no fields")
        total = sum(width for _, width, _, _ in fields)
        size_name = client.LAYOUTS[record][1]
        _need(total == found[size_name], f"wire: {layout_name} adds up to {total} bytes and {size_name} says {found[size_name]}")
        out.append(f"pub const {prefix}_LEN: usize = {total};\n")
        offset = 0
        for name, width, _, _ in fields:
            out.append(f"pub const OFF_{prefix}_{name.upper()}: usize = {offset};\n")
            offset += width
        out.append("\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n")
        out.append(f"pub struct {struct_name} {{\n")
        for name, width, signed, array in fields:
            out.append(f"    pub {name}: {rust_type(width, signed, array)},\n")
        out.append("}\n\n")
        out.append(f"impl {struct_name} {{\n")
        out.append(f"    pub fn decode(buf: &[u8]) -> Option<Self> {{\n        if buf.len() < {prefix}_LEN {{\n            return None;\n        }}\n        Some(Self {{\n")
        for name, width, signed, array in fields:
            out.append(f"            {name}: {_decode_expr(prefix, name, width, signed, array)},\n")
        out.append("        })\n    }\n\n")
        out.append(f"    pub fn encode(self) -> [u8; {prefix}_LEN] {{\n        let mut buf = [0u8; {prefix}_LEN];\n")
        for name, width, signed, array in fields:
            out.append(f"        {_encode_stmt(prefix, name, width, signed, array)}\n")
        out.append("        buf\n    }\n}\n\n")
    return "".join(out).rstrip("\n") + "\n"


def render_bindings(text: str | None = None) -> str:
    """The generated file: `render_raw` formatted by rustfmt, as `cargo fmt --check` requires of the proto crate."""
    raw = render_raw(text)
    process = subprocess.run(["rustfmt", "--edition", "2024", "--emit", "stdout"], input=raw, text=True, capture_output=True, check=False)
    _need(process.returncode == 0, f"wire: rustfmt refused the rendered Rust: {process.stderr[:200]}")
    # `--emit stdout` may put a file-name banner in front of the code; the header comment is the first line.
    start = process.stdout.find("// @generated")
    _need(start >= 0, "wire: rustfmt output has no generated header")
    return process.stdout[start:]


def read_exact(path) -> str:
    try:
        return path.read_bytes().decode("utf-8")
    except UnicodeDecodeError as error:
        raise WireError(f"{path.name} is not UTF-8 text: {error.reason}") from error


def check_generated_text(text: str, name: str) -> int:
    """The file equals the renderer's output byte for byte; returns the number of records it holds."""
    expected = render_bindings()
    if text != expected:
        seen, wanted = text.splitlines(keepends=True), expected.splitlines(keepends=True)
        for number in range(max(len(seen), len(wanted))):
            have = seen[number] if number < len(seen) else ""
            want = wanted[number] if number < len(wanted) else ""
            if have != want:
                raise WireError(f"{name} differs from the renderer's output at line {number + 1}: has {have.rstrip()[:60]!r}, wants {want.rstrip()[:60]!r}")
        raise WireError(f"{name} differs from the renderer's output")
    return len(RECORDS)


def check_generated() -> int:
    if not GENERATED.is_file():
        raise WireError(f"{GENERATED.relative_to(ROOT)} does not exist; the wire records have not landed, run `just zenoh_service_client_wire_gen`")
    return check_generated_text(read_exact(GENERATED), GENERATED.name)


# The values the Rust test encodes. Every field, reserved padding included, holds a distinct nonzero byte pattern,
# so a swapped, shifted, truncated or sign-extended field changes the bytes. The Rust test builds the same values.
MAGIC = client.PINNED["serviceMagic"]
VALUES = {
    "ServiceRequest": {
        "magic": MAGIC, "version": 1, "op": 2, "flags": 0x40, "row": 0x0201, "reserved": bytes([0xA1, 0xA2]),
        "sequence": -2, "reserved2": bytes(range(0xB0, 0xBC)),
    },
    "ServiceCompletion": {
        "magic": MAGIC, "version": 1, "op": 3, "item": 1, "status": -4, "row": 0x0102, "reserved": bytes([0xC1, 0xC2]),
        "length": 0x00001234, "flags": 1,
    },
    "SampleHeader": {"sequence": 0x1112131415161718, "timestamp": -1000},
    "ServiceLoan": {
        "magic": MAGIC, "version": 1, "role": 2, "reserved0": bytes([0xD1]), "buffer": 0x2122232425262728,
        "lease": 0x3132333435363738, "length": 4096, "reserved": bytes(range(0xE0, 0x100)),
    },
}


def pack(record: str, values: dict[str, object] | None = None, text: str | None = None) -> bytes:
    """The record's bytes from the schema's layout, written with `struct` and nothing generated."""
    text = client.SCHEMA.read_text(encoding="utf-8") if text is None else text
    layout_name = next(layout for name, layout, _, _ in RECORDS if name == record)
    values = VALUES[record] if values is None else values
    out = b""
    for name, width, signed, array in client.layout(text, layout_name):
        if array:
            out += bytes(values[name])
            _need(len(values[name]) == width, f"wire: {name} is {len(values[name])} bytes, the layout says {width}")
        else:
            code = {1: "b", 2: "h", 4: "i", 8: "q"}[width]
            try:
                out += struct.pack("<" + (code if signed else code.upper()), values[name])
            except struct.error as error:
                raise WireError(f"wire: {name} does not fit {width} {'signed' if signed else 'unsigned'} bytes: {error}") from error
    return out


# The number of fields on each kind of line, the word `clientwire` included.
SHAPES = {"size": 4, "encode": 4, "roundtrip": 4, "short": 4, "ok": 3}


def good_lines(text: str | None = None) -> list[str]:
    """The honest transcript, in the order the Rust test prints it, for the layouts in `text`."""
    out: list[str] = []
    for record, _layout, _struct, _prefix in RECORDS:
        out.append(f"clientwire size {RECORD_WORDS[record]} {len(pack(record, text=text))}")
    for record, *_ in RECORDS:
        out.append(f"clientwire encode {RECORD_WORDS[record]} {pack(record, text=text).hex()}")
    for record, *_ in RECORDS:
        out.append(f"clientwire roundtrip {RECORD_WORDS[record]} ok")
    for record, *_ in RECORDS:
        out.append(f"clientwire short {RECORD_WORDS[record]} refused")
    out.append("clientwire ok every-record-encodes-to-the-layout-and-decodes-back")
    return out


def judge(lines: list[str], text: str | None = None) -> tuple[int, int]:
    """Check a transcript against the exam for the layouts in `text`; returns (cases, refusals)."""
    for line in lines:
        fields = line.split()
        _need(fields[:1] == ["clientwire"], f"wire: a record that is not a clientwire exam line: {line!r}")
        _need(len(fields) > 1 and fields[1] in SHAPES, f"wire: unrecognised line: {line}")
        _need(len(fields) == SHAPES[fields[1]], f"wire: a {fields[1]} line has {len(fields)} fields: {line}")
    wanted = good_lines(text)
    for index, (seen, want) in enumerate(zip(lines, wanted, strict=False)):
        _need(seen == want, f"wire line {index + 1} is {seen!r}, the exam requires {want!r}")
    if len(lines) < len(wanted):
        raise WireError(f"wire: the transcript stops after {len(lines)} of {len(wanted)} lines; the next is {wanted[len(lines)]!r}")
    if len(lines) > len(wanted):
        raise WireError(f"wire: {len(lines) - len(wanted)} lines beyond the exam, the first {lines[len(wanted)]!r}")
    refusals = sum(1 for line in lines if line.startswith("clientwire short "))
    return len(lines) - refusals, refusals


def _change_last(line: str) -> str:
    head, last = line.rsplit(" ", 1)
    if re.fullmatch(r"[0-9a-f]+", last) and len(last) > 4:
        return f"{head} {last[:-1]}{'0' if last[-1] != '0' else '1'}"
    return f"{head} {last}x"


def transcript_mutations() -> list[tuple[str, list[str]]]:
    good = good_lines()
    out: list[tuple[str, list[str]]] = [
        ("an empty transcript", []),
        ("a line that is not a clientwire exam line", [*good, "service ok static-declaration-at-open"]),
        ("an unrecognised kind of line", [*good, "clientwire dropped request"]),
        ("a line with an extra field", [*good[:-1], good[-1] + " extra"]),
        ("a line repeated", [*good, good[-1]]),
        ("the last line missing", good[:-1]),
    ]
    for index, line in enumerate(good):
        out.append((f"line {index + 1} missing ({line[11:60]})", good[:index] + good[index + 1 :]))
    for index, line in enumerate(good):
        out.append((f"line {index + 1} with its last field changed ({line[11:60]})", [*good[:index], _change_last(line), *good[index + 1 :]]))
    return out


def transcript_controls() -> int:
    good = good_lines()
    judge(good)
    refused = 0
    for label, lines in transcript_mutations():
        if lines == good:
            raise WireError(f"control: {label} did not change the transcript")
        try:
            judge(lines)
        except WireError:
            refused += 1
            continue
        raise WireError(f"control: the wire judge accepted {label}")
    return refused


def generated_controls() -> int:
    """A generated file that differs from the renderer's output by one edit is refused."""
    honest = render_bindings()
    check_generated_text(honest, "honest")
    edits = [
        ("an offset changed", honest.replace("OFF_REQUEST_SEQUENCE: usize = 12", "OFF_REQUEST_SEQUENCE: usize = 13", 1)),
        ("a field type changed", honest.replace("pub sequence: i64", "pub sequence: u64", 1)),
        ("a little-endian read changed to big-endian", honest.replace("from_le_bytes", "from_be_bytes", 1)),
        ("a little-endian write changed to big-endian", honest.replace("to_le_bytes", "to_be_bytes", 1)),
        ("the length check removed", honest.replace("if buf.len() < REQUEST_LEN {\n            return None;\n        }\n", "", 1)),
        ("a field dropped from encode", honest.replace("        buf[OFF_REQUEST_ROW..OFF_REQUEST_ROW + 2].copy_from_slice(&self.row.to_le_bytes());\n", "", 1)),
        ("the header removed", honest[honest.index("\n", honest.index("\n") + 1) + 1 :]),
        ("a comment appended", honest + "// a comment\n"),
        ("a line ending changed to CRLF", honest.replace("\n", "\r\n")),
        ("the trailing newline removed", honest.rstrip("\n")),
        ("an empty file", ""),
    ]
    refused = 0
    for label, text in edits:
        if text == honest:
            raise WireError(f"control: {label} did not change the generated text")
        try:
            check_generated_text(text, "mutated")
        except WireError:
            refused += 1
            continue
        raise WireError(f"control: the wire judge accepted a generated file with {label}")
    return refused


def _block_comment(text: str) -> bool:
    """Whether a `/*` opens outside a line comment. The proto crate's header comment names `contracts/*/v1`, which is
    a path inside a line comment and opens nothing."""
    return any("/*" in line.split("//", 1)[0] for line in text.splitlines())


PROTO_LIB = ROOT / "components" / "proto" / "src" / "lib.rs"
WIRE_TEST = ROOT / "components" / "proto" / "tests" / "zenoh_service_client_wire.rs"
EXPORT_MOD = "pub mod zenoh_service_client_wire;"
TEST_IMPORT = "use slime_proto::zenoh_service_client_wire::{"


def check_export_text(text: str) -> None:
    """`slime-proto` exports the wire records. The Rust test may compile the generated file by path, which passes
    without the export, so the export is read as text.

    This matches the exact line the neighbouring modules use and rules out what could make it inert. It must stand
    alone at the start of its line, once, with no attribute directly above it. No block comment may appear in the
    file, since one could swallow the line, and no inline module may open at the top level, since one could wrap it."""
    lines = text.splitlines()
    _need(not _block_comment(text), "wire: lib.rs holds a block comment, which could hide the export")
    at = [index for index, line in enumerate(lines) if line == EXPORT_MOD]
    _need(len(at) == 1, f"wire: lib.rs holds {len(at)} lines `{EXPORT_MOD}`, the export needs exactly one")
    _need(at[0] >= 1 and not lines[at[0] - 1].lstrip().startswith("#["), "wire: an attribute stands directly above the export")
    wrappers = [line for line in lines if re.match(r"^(pub(\([a-z]+\))? )?mod \w+ *\{", line)]
    if wrappers:
        raise WireError(f"wire: lib.rs opens an inline module at the top level: {wrappers[0]!r}")


def check_test_text(text: str) -> None:
    """The Rust test reaches the records through the crate's API, so a consumer is compiled against the export. A
    test that includes the generated source by path proves nothing about the export."""
    _need(not _block_comment(text), "wire: the test holds a block comment, which could hide its import")
    lines = text.splitlines()
    _need(sum(1 for line in lines if line == TEST_IMPORT) == 1, f"wire: the test needs exactly one line `{TEST_IMPORT}`")
    _need(not any(re.match(r"^\s*#\[path\b", line) for line in lines), "wire: the test includes a source file by path")
    _need(not any(re.match(r"^\s*(pub )?mod \w+;", line) for line in lines), "wire: the test declares a module from a file")


def check_exports() -> None:
    for path, check in ((PROTO_LIB, check_export_text), (WIRE_TEST, check_test_text)):
        _need(path.is_file(), f"wire: {path.relative_to(ROOT)} does not exist")
        check(path.read_text(encoding="utf-8"))


_HONEST_LIB = "\n".join(["#![no_std]", "", "pub mod syscall_abi;", "pub mod zenoh_service_client;", EXPORT_MOD, "pub mod zenoh_service_grants;", ""])
_HONEST_TEST = "\n".join(["use slime_proto::zenoh_service_client_wire::{", "    WireServiceRequest,", "};", "", "#[test]", "fn a() {}", ""])


def export_controls() -> int:
    """The export check and the test check refuse what would leave the records unexported or unproved."""
    check_export_text(_HONEST_LIB)
    check_test_text(_HONEST_TEST)
    lib_edits = [
        ("the export removed", _HONEST_LIB.replace(EXPORT_MOD + "\n", "")),
        ("the export commented out", _HONEST_LIB.replace(EXPORT_MOD, "// " + EXPORT_MOD)),
        ("the export in a block comment", _HONEST_LIB.replace(EXPORT_MOD, "/* " + EXPORT_MOD + " */")),
        ("the export under a cfg attribute", _HONEST_LIB.replace(EXPORT_MOD, "#[cfg(test)]\n" + EXPORT_MOD)),
        ("the export under a never-true attribute", _HONEST_LIB.replace(EXPORT_MOD, "#[cfg(any())]\n" + EXPORT_MOD)),
        ("the export indented", _HONEST_LIB.replace(EXPORT_MOD, "    " + EXPORT_MOD)),
        ("the export in an inline module", _HONEST_LIB.replace(EXPORT_MOD, "mod hidden {\n" + EXPORT_MOD + "\n}")),
        ("a private module", _HONEST_LIB.replace(EXPORT_MOD, "mod zenoh_service_client_wire;")),
        ("another module name", _HONEST_LIB.replace(EXPORT_MOD, "pub mod zenoh_service_client_wires;")),
        ("the export twice", _HONEST_LIB.replace(EXPORT_MOD, EXPORT_MOD + "\n" + EXPORT_MOD)),
        ("an empty file", ""),
    ]
    test_edits = [
        ("the import removed", _HONEST_TEST.replace(TEST_IMPORT, "use std::fmt::{")),
        ("the generated file included by path", "#[path = \"../src/zenoh_service_client_wire.rs\"]\nmod wire_by_path;\n" + _HONEST_TEST),
        ("a path attribute beside the import", "    #[path = \"x.rs\"]\n" + _HONEST_TEST),
        ("a module declared from a file", "mod wire;\n" + _HONEST_TEST),
        ("the import in a block comment", _HONEST_TEST.replace(TEST_IMPORT, "/* " + TEST_IMPORT + " */")),
        ("the import twice", _HONEST_TEST.replace(TEST_IMPORT, TEST_IMPORT + "\n};\n" + TEST_IMPORT)),
        ("an empty file", ""),
    ]
    refused = 0
    for edits, honest, check in ((lib_edits, _HONEST_LIB, check_export_text), (test_edits, _HONEST_TEST, check_test_text)):
        for label, text in edits:
            if text == honest:
                raise WireError(f"control: {label} did not change the file")
            try:
                check(text)
            except WireError:
                refused += 1
                continue
            raise WireError(f"control: the wire export check accepted {label}")
    return refused


def all_controls() -> int:
    return transcript_controls() + generated_controls() + reference_controls() + export_controls()


# What the admitted item fixes, held here as well so the gate stays correct after the item is completed and
# retired to .tasks/terminal. Both counts are exact.
PINNED_CASES = 17
PINNED_CONTROLS = 76
ADMISSION = "slime-zenoh-service-wire-"


def item_pins() -> tuple[int, int]:
    """The case count and the control count the admitted item fixes, read from its stored body, or (0, 0)."""
    for path in sorted((ROOT / ".tasks" / "items").glob("*.md")):
        text = path.read_text(encoding="utf-8")
        if "zenoh_service_client_wire_check" not in text or ADMISSION not in text or re.search(r"^state: cancelled$", text, re.M):
            continue
        found = re.search(r'id = "all-cases-observed";.*?intValue = (\d+);', text, re.S)
        controls = re.search(r'id = "exactly-\d+-controls";.*?observation = "negativeControlsRefused";.*?intValue = (\d+);', text, re.S)
        if found and controls:
            return int(found.group(1)), int(controls.group(1))
    return 0, 0


def reference_controls() -> int:
    """The judge reads the layouts from the schema. For each corrupted schema, the transcript an honest encoder of the
    real layouts prints must be refused, because the judge now requires the bytes of the corrupted layouts."""
    text = client.SCHEMA.read_text(encoding="utf-8")
    honest = good_lines(text)
    judge(honest, text)
    edits = [
        ("the request row narrowed", "requestLayout", '{ name = "row"; width = 2; signed = false; byteArray = false; };\n  { name = "reserved"; width = 2;', '{ name = "row"; width = 1; signed = false; byteArray = false; };\n  { name = "reserved"; width = 3;'),
        ("the request sequence made unsigned", "requestLayout", '{ name = "sequence"; width = 8; signed = true;', '{ name = "sequence"; width = 8; signed = false;'),
        ("the completion status made unsigned", "completionLayout", '{ name = "status"; width = 4; signed = true;', '{ name = "status"; width = 4; signed = false;'),
        ("two completion fields swapped", "completionLayout", '{ name = "length"; width = 4; signed = false; byteArray = false; };\n  { name = "flags"; width = 4; signed = false; byteArray = false; };', '{ name = "flags"; width = 4; signed = false; byteArray = false; };\n  { name = "length"; width = 4; signed = false; byteArray = false; };'),
        ("the sample timestamp made unsigned", "sampleHeaderLayout", '{ name = "timestamp"; width = 8; signed = true;', '{ name = "timestamp"; width = 8; signed = false;'),
        ("the loan lease narrowed", "loanLayout", '{ name = "lease"; width = 8; signed = false; byteArray = false; };\n  { name = "length"; width = 8;', '{ name = "lease"; width = 4; signed = false; byteArray = false; };\n  { name = "length"; width = 8;'),
        ("the loan reserved bytes widened", "loanLayout", '{ name = "reserved"; width = 32;', '{ name = "reserved"; width = 33;'),
    ]
    refused = 0
    for label, layout_name, old, new in edits:
        block = re.search(rf"^{layout_name} :: List WireField = \{{\n(.*?)^\}};", text, re.M | re.S)
        if block is None or block.group(0).count(old) != 1:
            raise WireError(f"control: {label} anchor is not in {layout_name} exactly once")
        mutated = text.replace(block.group(0), block.group(0).replace(old, new, 1))
        if mutated == text:
            raise WireError(f"control: {label} did not change the schema")
        try:
            judge(honest, mutated)
        except WireError:
            refused += 1
            continue
        raise WireError(f"control: the wire judge accepted the honest transcript under a schema with {label}")
    return refused
